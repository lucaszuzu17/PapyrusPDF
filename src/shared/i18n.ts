export const DICTS: Record<UiLang, Record<I18nKey, string>> = { pt, en, es };

export function translate(lang: UiLang, key: I18nKey, vars?: Record<string, string | number>): string {
  let out = DICTS[lang][key] ?? DICTS.pt[key];
  if (vars) {
    out = out.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  }
  return out;
}
