// Internacionalização 100% offline (Português, Inglês e Espanhol) seguindo o idioma do sistema.

export type UiLang = "pt" | "en" | "es";
export type LangPref = "auto" | UiLang;

/** Resolve a preferência ("auto" ou idioma fixo) para um dos idiomas suportados. */
export function resolveLang(pref: LangPref | string | null | undefined, systemLocale?: string): UiLang {
  if (pref === "pt" || pref === "en" || pref === "es") return pref;
  const raw = (systemLocale ?? (typeof navigator !== "undefined" ? navigator.language : "") ?? "").trim().toLowerCase();
  if (raw.startsWith("pt")) return "pt";
  if (raw.startsWith("es")) return "es";
  return "en";
}

export function localeTag(lang: UiLang): string {
  return lang === "pt" ? "pt-BR" : lang === "es" ? "es-ES" : "en-US";
}

export function defaultOcrLang(lang: UiLang): string {
  return lang === "pt" ? "por" : lang === "es" ? "spa" : "eng";
}

export function formatDecimal(value: number, digits: number, lang: UiLang): string {
  const s = value.toFixed(digits);
  return lang === "en" ? s : s.replace(".", ",");
}

export function formatBytes(bytes: number, lang: UiLang): string {
  if (bytes >= 1048576) return `${formatDecimal(bytes / 1048576, 1, lang)} MB`;
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

